-- 011: право на правку скриптов — отдельно от доступа к аналитике.
--
-- Пользователь админки один на все продукты: вошёл — видит и «Скрипты», и
-- «Аналитику». Права при этом у продуктов свои:
--   аналитика — access_scope: own (только свои смены) | all (все смены и
--               администрирование: сотрудники, метрики, точки);
--   скрипты   — scripts_access: read (читает и копирует) | edit (правит).
--
-- Раньше правка скриптов выводилась из access_scope = 'all'. Чтобы после
-- обновления никто не потерял права, которые у него уже были, им сразу
-- ставится edit.
--
-- Выполнить ДО выкатки кода: без колонки не откроется вход в админку.
-- Безопасно для повторного запуска.

begin;

alter table employees
    add column if not exists scripts_access varchar(16) not null default 'read';

update employees
   set scripts_access = 'edit'
 where access_scope = 'all' and scripts_access = 'read';

commit;
