-- 009: момент последней смены статуса смены.
--
-- Нужен, чтобы отличить разбор, который идёт, от разбора, который умер вместе
-- с воркером (убит по памяти, по лимиту времени, при передеплое) и остался в
-- «обрабатывается» навсегда. Раньше такую смену нельзя было ни пересчитать,
-- ни удалить — API отвечало «уже в очереди». Теперь смена, у которой статус
-- не двигался несколько часов, считается зависшей, и кнопки снова доступны.
--
-- Безопасно для повторного запуска.

begin;

alter table day_recordings
    add column if not exists status_changed_at timestamptz;

update day_recordings set status_changed_at = created_at where status_changed_at is null;

commit;
